#!/usr/bin/env python3
"""Converts the Android app's StaffGlyphs.java (Noto Music outlines) to Sources/StaffGlyphs.swift."""
import re, sys
src = open(sys.argv[1]).read()
out = ["// Generated by tools/glyphs_to_swift.py from the Android app's StaffGlyphs.java",
       "// (outlines from Noto Music, SIL Open Font License). Don't edit.", "",
       "enum StaffGlyphs {"]
for name, val in re.findall(r"static final float (\w+) = ([-\d.]+)f;", src):
    out.append(f"    static let {name.lower()}: Double = {val}".replace("_width", "Width").replace("g_clef", "gClef").replace("f_clef", "fClef"))
for name, body in re.findall(r"static final float\[\]\[\] (\w+) = \{(.*?)\n    \};", src, re.S):
    rows = re.findall(r"\{([^{}]*)\}", body)
    swift = name.lower().replace("g_clef", "gClef").replace("f_clef", "fClef")
    out.append(f"    static let {swift}: [[Double]] = [")
    for r in rows:
        nums = [n.strip().rstrip("f") for n in r.split(",") if n.strip()]
        out.append("        [" + ", ".join(nums) + "],")
    out.append("    ]")
out.append("}")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
